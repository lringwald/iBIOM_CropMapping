#!/usr/bin/env Rscript
# =============================================================================
# gen_config.R — generate shell defaults, JSON Schema, and config.json from config/knobs.json
# =============================================================================
if (!requireNamespace("jsonlite", quietly = TRUE)) {
  stop("jsonlite is required to run tools/gen_config.R")
}

reg <- jsonlite::fromJSON("config/knobs.json", simplifyVector = FALSE)$knobs
nm  <- vapply(reg, `[[`, "", "name")
esc <- function(x) gsub("'", "'\\\\''", as.character(x))

# ---- 1. Shell knob registry (config/knobs.generated.sh) ----------------------
sh <- c(
  "# GENERATED by tools/gen_config.R from config/knobs.json -- do not edit.",
  "# Edit config/knobs.json and re-run: Rscript tools/gen_config.R",
  "",
  sprintf("KNOB_REGISTRY=(%s)", paste(sprintf("'%s'", nm), collapse = " "))
)

for (k in reg) {
  env_name <- if (!is.null(k$env) && nzchar(k$env)) k$env else k$name
  sh <- c(
    sh,
    sprintf("KNOB_ENV_%s='%s'",     k$name, esc(env_name)),
    sprintf("KNOB_TYPE_%s='%s'",    k$name, esc(k$type)),
    sprintf("KNOB_DEFAULT_%s='%s'", k$name, esc(k$default)),
    sprintf("KNOB_BLANK_%s='%s'",   k$name, esc(k$blank)),
    sprintf("KNOB_SCOPE_%s='%s'",   k$name, esc(k$scope))
  )
}
dir.create("config", recursive = TRUE, showWarnings = FALSE)
writeLines(sh, "config/knobs.generated.sh")

# ---- 2. WKUBE Routine Configuration Schema (docs/routine_config.schema.json) --
props <- lapply(reg, function(k) {
  def_str <- as.character(k$default)
  blank_default <- !nzchar(def_str)
  title <- if (!is.null(k$label) && nzchar(k$label)) k$label else k$name
  desc  <- sprintf("%s -- %s", title, k$desc)
  if (blank_default) {
    blank_str <- as.character(k$blank)
    desc <- sprintf("%s OPTIONAL: leave empty for %s.", desc,
                    if (nzchar(blank_str)) blank_str else "empty/default")
  }
  p <- list(
    type        = k$type,
    title       = title,
    description = desc,
    default     = k$default
  )
  if (!is.null(k$enum))    p$enum    <- k$enum
  if (!is.null(k$minimum)) p$minimum <- k$minimum
  if (!is.null(k$maximum)) p$maximum <- k$maximum
  p
})
names(props) <- nm

schema <- list(
  `$schema`   = "http://json-schema.org/draft-07/schema#",
  type        = "object",
  title       = "iBIOM European Pasture, Livestock & Crop Mapping WKUBE Routine",
  description = paste(
    "GENERATED from config/knobs.json by tools/gen_config.R.",
    "Resolves hosted iBIOM_Explorer/Land_use_and_management/<year>/ibiom_LUM_europe_100m_<year>.tif",
    "rasters and executes the non-GLOBIOM Pasture & Ruminant Livestock downscaling routine",
    "(using cascadecore::fienberg) and/or Cropland mapping routine inside IIASA Accelerator WKUBE."
  ),
  required    = list("TASK"),
  properties  = props
)

dir.create("docs", recursive = TRUE, showWarnings = FALSE)
jsonlite::write_json(schema, "docs/routine_config.schema.json",
                     auto_unbox = TRUE, pretty = TRUE, null = "null")

# ---- 3. Active default config JSON (config/config.json + config.json) --------
default_cfg <- list()
for (k in reg) {
  default_cfg[[k$name]] <- k$default
}
jsonlite::write_json(default_cfg, "config/config.json", auto_unbox = TRUE, pretty = TRUE)
jsonlite::write_json(default_cfg, "config.json", auto_unbox = TRUE, pretty = TRUE)

cat(sprintf("Wrote config/knobs.generated.sh (%d knobs), docs/routine_config.schema.json, config/config.json, and config.json\n", length(reg)))

